    -e OMP_NUM_THREADS=1 \
    -e MKL_NUM_THREADS=1 \
    -e OPENBLAS_NUM_THREADS=1 \
    -v "$PROJECT_ROOT:/workspace" \
    -w /workspace \
    "$IMAGE" \
