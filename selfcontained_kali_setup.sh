python3 "$PROJECT_ROOT/tools/generate_synthetic_calibration.py" \
    --output-dir "$CALIB_DIR" \
    --samples 10 \
    --shape 1,3,224,224

# -----------------------------------------------------------------------------
# 4. Load OpenExplorer Docker image
# -----------------------------------------------------------------------------
IMAGE="openexplorer/ai_toolchain_ubuntu_20_x5_cpu:v1.2.8-py310"
if ! docker images --format '{{.Repository}}:{{.Tag}}' | grep -qxF "$IMAGE"; then
    echo "Trying docker pull with USTC mirror ..."
    mkdir -p /etc/docker
    cat > /etc/docker/daemon.json <<EOF
{"registry-mirrors":["https://docker.mirrors.ustc.edu.cn"]}
