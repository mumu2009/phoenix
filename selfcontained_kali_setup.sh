echo "Exporting I-JEPA ONNX to $OUT_DIR ..."
python3 "$PROJECT_ROOT/tools/export_ijepa_onnx.py" \
    --variant facebook/ijepa_vith14_1k \
    --output-dir "$OUT_DIR" \
    --resolution 224 \
    --output-dim 128

# -----------------------------------------------------------------------------
# 3. Synthetic calibration data
# -----------------------------------------------------------------------------
CALIB_DIR="$PROJECT_ROOT/runtime_store/calibration/ijepa_vith14_1k_featuremap"
